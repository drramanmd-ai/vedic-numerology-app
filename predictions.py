def analyze_name_compatibility(first_name, full_name, root, destiny):
    """
    Checks name compound values for first name and full name.
    Evaluates vibration and action recommended based on Action Table.
    Checks compatibility with root and destiny number.
    Returns analysis results dict.
    """
    import numerology as num_engine
    
    # 1. Calculate compound values using Chaldean
    first_val = num_engine.calculate_compound_value(first_name) if first_name else 0
    full_val = num_engine.calculate_compound_value(full_name) if full_name else 0
    
    # Standardize values to range 1-80 if greater than 80
    def reduce_to_80(val):
        while val > 80:
            val = sum(int(d) for d in str(val))
        return val

    first_val_reduced = reduce_to_80(first_val)
    full_val_reduced = reduce_to_80(full_val)
    
    # 2. Get positive/negative aura
    first_info = COMPOUND_NUMBERS.get(first_val_reduced, {"aura": "-", "summary": "Unknown", "description": ""})
    full_info = COMPOUND_NUMBERS.get(full_val_reduced, {"aura": "-", "summary": "Unknown", "description": ""})
    
    first_aura = first_info.get("aura", "-")
    full_aura = full_info.get("aura", "-")
    
    # 3. Determine action from the Action Table
    # First Name (+) and Full Name (-) -> Drop Last Name
    # First Name (-) and Full Name (-) -> Change Name
    # First Name (-) and Full Name (+) -> Change Name
    # First Name (+) and Full Name (+) -> No Change (subject to compatibility)
    action = "Change Name"
    if first_aura == "+" and full_aura == "+":
        action = "No Change"
    elif first_aura == "+" and full_aura == "-":
        action = "Drop Last Name"
    elif first_aura == "-" and full_aura == "+":
        action = "Change Name"
    elif first_aura == "-" and full_aura == "-":
        action = "Change Name"
        
    # Check compatibility for single digit of Full Name compound number
    single_digit = num_engine.reduce_digit(full_val_reduced)
    rel_root = num_engine.get_relationship(root, single_digit)
    rel_dest = num_engine.get_relationship(destiny, single_digit)
    
    compatibility_ok = True
    comp_reason = ""
    
    if rel_root == "Enemy":
        compatibility_ok = False
        comp_reason += f"Enemy to Root Number {root}. "
    if rel_dest == "Enemy":
        compatibility_ok = False
        comp_reason += f"Enemy to Destiny Number {destiny}. "
        
    if action == "No Change" and not compatibility_ok:
        action = "Change Name"
        comp_reason = "Although compounds are positive, the name single digit is incompatible with your core numbers: " + comp_reason
        
    # 4. Suggest target friendly numbers
    # Get all friendly numbers for both root and destiny
    friends_root = num_engine.FRIENDSHIP_TABLE.get(root, (set(), set(), set()))[0]
    friends_dest = num_engine.FRIENDSHIP_TABLE.get(destiny, (set(), set(), set()))[0]
    
    # Friendly to both
    common_friends = friends_root.intersection(friends_dest)
    if not common_friends:
        # Fallback to union or at least friendly to either, but preferably not enemy to either
        common_friends = (friends_root.union(friends_dest))
        # Remove enemies of either
        enemies_root = num_engine.FRIENDSHIP_TABLE.get(root, (set(), set(), set()))[2]
        enemies_dest = num_engine.FRIENDSHIP_TABLE.get(destiny, (set(), set(), set()))[2]
        common_friends = common_friends - enemies_root - enemies_dest
        
    # Find positive compound numbers (1-80) that reduce to these friendly digits
    target_compounds = []
    for comp_num in sorted(COMPOUND_NUMBERS.keys()):
        if COMPOUND_NUMBERS[comp_num]["aura"] == "+":
            reduced = num_engine.reduce_digit(comp_num)
            if reduced in common_friends:
                target_compounds.append(comp_num)
                
    # Format results
    res = {
        "first_name": first_name,
        "first_val": first_val_reduced,
        "first_aura": first_aura,
        "first_summary": first_info.get("summary", ""),
        "first_desc": first_info.get("description", ""),
        
        "full_name": full_name,
        "full_val": full_val_reduced,
        "full_aura": full_aura,
        "full_summary": full_info.get("summary", ""),
        "full_desc": full_info.get("description", ""),
        
        "single_digit": single_digit,
        "rel_root": rel_root,
        "rel_dest": rel_dest,
        "compatibility_ok": compatibility_ok,
        "comp_reason": comp_reason,
        
        "action": action,
        "target_compounds": target_compounds,
        "common_friends": list(common_friends)
    }
    return res


